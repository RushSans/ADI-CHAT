def create_session_token(user_id: int) -> str:
    """
    Создает подписанный токен для идентификации пользователя.
    
    Процесс:
    1. Берет ID пользователя как строку
    2. Создает HMAC-подпись используя SECRET_KEY
    3. Объединяет ID и подпись через точку
    
    Формат токена: "user_id.signature"
    
    Аргументы:
        user_id: ID пользователя в БД
        
    Возвращает:
        Строка с токеном: "user_id.signature"
    
    Пример:
        create_session_token(1) -> "1.a1b2c3d4e5f6..."
    """
    # Преобразуем ID в строку (основная часть токена)
    payload = str(user_id)
    
    # Создаем HMAC-подпись
    # HMAC-SHA256 гарантирует, что никто не сможет подделать токен
    sig = hmac.new(
        SECRET_KEY.encode(),  # Секретный ключ в байтах
        payload.encode(),     # Данные для подписи
        hashlib.sha256        # Алгоритм хэширования
    ).hexdigest()
    
    # Возвращаем ID и подпись, разделенные точкой
    return f"{payload}.{sig}"


def verify_session_token(token: str | None) -> int | None:
    """
    Проверяет валидность сессионного токена и возвращает ID пользователя.
    
    Процесс:
    1. Проверяет формат токена (должен содержать точку)
    2. Разделяет на ID и подпись
    3. Проверяет, что ID - это число
    4. Вычисляет ожидаемую подпись
    5. Сравнивает подписи (защищенно)
    
    Аргументы:
        token: строка с токеном (или None)
        
    Возвращает:
        ID пользователя (int), если токен валидный
        None, если токен невалидный или отсутствует
    
    Пример:
        verify_session_token("1.a1b2c3d4e5f6...") -> 1
        verify_session_token("invalid_token") -> None
        verify_session_token(None) -> None
    """
    # --- 1. Проверка наличия и формата токена ---
    if not token or "." not in token:
        return None
    
    # Разделяем на ID и подпись (rsplit на случай, если в ID есть точки)
    payload, sig = token.rsplit(".", 1)
    
    # --- 2. Проверка, что ID - число ---
    if not payload.isdigit():
        return None
    
    # --- 3. Вычисляем ожидаемую подпись для данного ID ---
    expected = hmac.new(
        SECRET_KEY.encode(),
        payload.encode(),
        hashlib.sha256
    ).hexdigest()
    
    # --- 4. Сравниваем подписи (защищенно от timing attacks) ---
    if not hmac.compare_digest(sig, expected):
        return None  # Подпись не совпадает - токен поддельный
    
    # Токен валидный - возвращаем ID пользователя
    return int(payload)


