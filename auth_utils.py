def hash_password(password: str) -> str:
    """
    Хэширует пароль с использованием соли и алгоритма PBKDF2.
    
    Процесс:
    1. Генерируется случайная соль (16 байт в hex-формате)
    2. Пароль + соль хэшируются алгоритмом PBKDF2-HMAC-SHA256
    3. Итераций: 100,000 (защита от брутфорса)
    4. Результат сохраняется в формате: "соль$хэш"
    
    Аргументы:
        password: пароль в открытом виде
        
    Возвращает:
        Строка с солью и хэшем: "соль$хэш"
    
    Пример:
        hash_password("demo1234") 
        -> "a1b2c3d4e5f6...$e8d9c7b6a5..."
    """
    # Генерируем криптографически безопасную случайную соль
    salt = secrets.token_hex(16)  # 16 байт = 32 символа в hex
    
    # Хэшируем пароль с солью
    # 100,000 итераций - хороший баланс между безопасностью и производительностью
    pwd_hash = hashlib.pbkdf2_hmac(
        "sha256",           # Алгоритм хэширования
        password.encode(),  # Пароль в байтах
        salt.encode(),      # Соль в байтах
        100_000             # Количество итераций
    )
    
    # Возвращаем соль и хэш, разделенные знаком $
    return f"{salt}${pwd_hash.hex()}"


def verify_password(password: str, stored: str) -> bool:
    """
    Проверяет, соответствует ли введенный пароль сохраненному хэшу.
    
    Процесс:
    1. Извлекает соль и хэш из сохраненной строки
    2. Хэширует введенный пароль с той же солью
    3. Сравнивает хэши (защищенно от атак по времени)
    
    Аргументы:
        password: пароль для проверки (в открытом виде)
        stored: сохраненная строка с солью и хэшем
        
    Возвращает:
        True, если пароль правильный, False в противном случае
    
    Пример:
        verify_password("demo1234", "a1b2...$e8d9...") -> True
    """
    # Поддержка старого формата (без соли) - для обратной совместимости
    if "$" not in stored:
        # Простое сравнение (небезопасно, но используется для миграции)
        return hmac.compare_digest(password, stored)
    
    # Разделяем соль и хэш
    salt, pwd_hash = stored.split("$", 1)
    
    # Хэшируем введенный пароль с той же солью
    new_hash = hashlib.pbkdf2_hmac(
        "sha256",
        password.encode(),
        salt.encode(),
        100_000
    )
    
    # Безопасное сравнение хэшей (защита от timing attacks)
    # hmac.compare_digest - сравнивает строки за постоянное время
    return hmac.compare_digest(new_hash.hex(), pwd_hash)


def needs_rehash(stored: str) -> bool:
    """
    Проверяет, нужно ли перехэшировать пароль.
    
    Используется для обновления старых паролей до нового формата.
    Если пароль хранится в старом формате (без соли), его нужно обновить.
    
    Аргументы:
        stored: сохраненная строка с паролем
        
    Возвращает:
        True, если пароль в старом формате (нужно обновить)
        False, если пароль уже в новом формате (с солью)
    
    Пример:
        needs_rehash("plain_password") -> True
        needs_rehash("salt$hash") -> False
    """
    # Если в сохраненном пароле нет $, значит это старый формат (без соли)
    return "$" not in stored


